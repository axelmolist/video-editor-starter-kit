#!/usr/bin/env python3
"""Propagate config/brand.json to every renderer. Run after /setup and after any brand change.

Writes (all gitignored, regenerated on demand):
    remotion/src/brand.generated.json   palette, font families, font faces, logo, fps for Remotion
    remotion/public/fonts/*             copies of the font files named in brand.json
    remotion/public/brand/*             copies of the logos
    design-studio/brand.css             CSS custom properties for HTML/CSS (HyperFrames) stills and animations
    design-studio/fonts-embedded.css    the font files as base64 data: URIs (link LAST; see design-studio/README.md)

Until /setup has run, config/brand.example.json is used so the projects still build.
"""
import base64
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "video" / "lib"))
import kitconfig  # noqa: E402


def main():
    b = kitconfig.brand()
    pub = ROOT / "remotion" / "public"
    (pub / "fonts").mkdir(parents=True, exist_ok=True)
    (pub / "brand").mkdir(parents=True, exist_ok=True)

    faces, seen = [], set()
    for role in ("title", "body", "captions"):
        f = b["fonts"][role]
        for key, weight in (("file", "400"), ("bold_file", "700")):
            src = f.get(key)
            if not src:
                continue
            p = Path(src).expanduser()
            p = p if p.is_absolute() else ROOT / p
            if not p.exists():
                print(f"warning: font file not found for {role}.{key}: {p}", file=sys.stderr)
                continue
            if (f["name"], weight) in seen:
                continue
            seen.add((f["name"], weight))
            shutil.copy2(p, pub / "fonts" / p.name)
            faces.append({"family": f["name"], "weight": weight, "file": p.name})

    logo = ""
    for key in ("light", "dark", "mark"):
        src = b.get("logos", {}).get(key)
        if src and (ROOT / src).exists():
            shutil.copy2(ROOT / src, pub / "brand" / Path(src).name)
            if not logo:  # light first, then dark, then mark
                logo = "brand/" + Path(src).name

    gen = {
        "brand_name": b["brand_name"],
        "fps": b["output"]["fps"],
        "palette": {k: b["palette"][k] for k in ("background", "primary", "accent", "text", "muted")},
        "fonts": {r: b["fonts"][r]["name"] for r in ("title", "body", "captions")},
        "faces": faces,
        "logo": logo,
    }
    (ROOT / "remotion" / "src" / "brand.generated.json").write_text(json.dumps(gen, indent=2) + "\n")

    css = [":root {"]
    for k, v in b["palette"].items():
        if isinstance(v, str):
            css.append(f"  --{k}: {v};")
    for k, v in b["palette"].get("extras", {}).items():
        css.append(f"  --{k}: {v};")
    for r in ("title", "body", "captions"):
        css.append(f'  --font-{r}: "{b["fonts"][r]["name"]}";')
    css.append("}")
    # HyperFrames does not load url(file://) fonts: register faces by local() name.
    for r in ("title", "body", "captions"):
        f = b["fonts"][r]
        css.append(f'@font-face {{ font-family: "{f["name"]}"; src: local("{f["name"]}"); font-weight: 400; }}')
        css.append(f'@font-face {{ font-family: "{f["name"]}"; src: local("{f.get("bold_name") or f["name"]}"); font-weight: 700; }}')
    (ROOT / "design-studio" / "brand.css").write_text("\n".join(css) + "\n")

    emb = []
    mime = {".otf": "font/otf", ".ttf": "font/ttf", ".woff2": "font/woff2", ".woff": "font/woff"}
    for face in faces:
        p = pub / "fonts" / face["file"]
        if p.suffix.lower() not in mime:
            continue  # .ttc collections cannot be embedded; install the font on the system instead
        data = base64.b64encode(p.read_bytes()).decode()
        emb.append(f'@font-face {{ font-family: "{face["family"]}"; font-weight: {face["weight"]}; '
                   f'src: url(data:{mime[p.suffix.lower()]};base64,{data}); }}')
    (ROOT / "design-studio" / "fonts-embedded.css").write_text(
        "/* generated by scripts/apply_brand.py - do not edit */\n" + "\n".join(emb) + "\n")

    src = "config/brand.json" if kitconfig.BRAND_PATH.exists() else "config/brand.example.json (run /setup)"
    print(f"brand applied from {src}: {len(faces)} font face(s), logo={'yes' if logo else 'none'}")


if __name__ == "__main__":
    main()
